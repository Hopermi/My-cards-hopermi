/** Направление свайпа. */
export type SwipeDir = 'right' | 'left' | 'up' | 'down';

/** Карточка-вопрос. */
export interface QuestionCard {
  /** Стабильный id: по нему считается матч, он же используется как key в колоде. */
  id: string;
  /** Текст вопроса. */
  text: string;
  /** Название категории, показывается на карточке. */
  category: string;
  /** CSS-градиент категории. Берите тёмные тона, чтобы белый текст проходил WCAG AA. */
  gradient: string;
  /** Подсказки для ответа. Если задано, на карточке появляется призыв нажать для деталей. */
  hint?: string;
}

/** Итог свайпа: что свайпнули и в какую сторону. */
export interface SwipeResult {
  dir: SwipeDir;
  card: QuestionCard;
}

/** Императивный API карточки, нужен кнопкам вне колоды. */
export interface SwipeCardHandle {
  /** Запускает вылет карточки в сторону `dir`. Повторные вызовы во время вылета игнорируются. */
  swipe: (dir: SwipeDir) => void;
  /** Отменяет текущий жест или вылет, который ещё не завершился, и возвращает карточку на место. */
  cancel: () => void;
}
